#!/usr/bin/env bash
#
# profile-repo.sh — probe a checked-out repo and emit PROJECT-FACTS.md: the
# durable, verifiable facts a contribution plan needs, so every plan stops
# re-deriving them from scratch.
#
# WHY
#
# screen-issues.sh answers "is this issue available?" and review-plan.sh answers
# "is this plan wrong?", but neither carries any project knowledge. Every plan
# therefore re-discovered the same things — where the API types live, which make
# target regenerates what, whether commit messages may contain "#123", that
# k8s/**/*.yaml is globbed into release assets. Several review findings across the
# #1214 plan were nothing more than one of those facts, learned late.
#
# WHAT THIS DOES NOT DO
#
# It emits only what it can VERIFY by probing: file paths, counts, make targets,
# tool versions, generated-artifact locations, CI job names. It flags but does not
# invent architecture or intent. A "⚠ VERIFY" line means "a human must confirm
# this before a plan relies on it".
#
# TRAP THIS TOOL EXISTS TO AVOID: naive counting. On kubernetes-sigs/agent-sandbox,
# `find -name '*.py'` returned 22,012 files; 21,832 of them were vendored virtualenvs
# under bin/ and the real number was 180. A generated fact that is wrong is worse than no fact,
# because plans will cite it.

set -euo pipefail

REPO_DIR="${REPO_DIR:-$PWD}"
OUT="${OUT:-}"
REPO_SLUG="${REPO_SLUG:-}"

RED=$'\033[0;31m'; GRN=$'\033[0;32m'; YLW=$'\033[0;33m'; BLU=$'\033[0;34m'; NC=$'\033[0m'
[[ -t 2 ]] || { RED=""; GRN=""; YLW=""; BLU=""; NC=""; }
log()  { printf '%s[info]%s %s\n' "$BLU" "$NC" "$*" >&2; }
warn() { printf '%s[warn]%s %s\n' "$YLW" "$NC" "$*" >&2; }
die()  { printf '%s[error]%s %s\n' "$RED" "$NC" "$*" >&2; exit 2; }

usage() {
  cat <<'EOF'
Usage: profile-repo.sh [options]

Probes a checked-out repository and writes PROJECT-FACTS.md — the verifiable
facts contribution plans keep needing. Read-only; never modifies the repo.

Options:
  --repo-dir DIR    Repository to probe (default: current directory)
  --repo SLUG       OWNER/NAME, for GitHub-side probes (CI, labels). Auto-detected
                    from the git remote when omitted.
  --out FILE        Write here (default: stdout)
  -h, --help        This help

Examples:
  profile-repo.sh --repo-dir ~/src/myproject --out PROJECT-FACTS.md
  profile-repo.sh > /tmp/facts.md
EOF
}

# Exclusions that make counts meaningful rather than impressive. Without these,
# vendored dependencies dominate every number.
PRUNE=( -not -path '*/.git/*' -not -path '*/vendor/*' -not -path '*/node_modules/*'
        -not -path '*/site-packages/*' -not -path '*venv*' -not -path '*/__pycache__/*'
        -not -path '*/dist/*' -not -path '*/build/*' -not -path '*/bin/*'
        -not -path '*/target/*' -not -path '*/.venv/*' )

count_ext() { find "$REPO_DIR" -type f -name "*.$1" "${PRUNE[@]}" 2>/dev/null | wc -l | tr -d ' '; }

# Largest source files: where the real logic lives, and what a newcomer must read.
# Split tests from implementation: the biggest files in most repos are test files,
# but a newcomer asking "where does the logic live" wants the implementation.
# Ranking tests first made the output actively misleading on the first run.
biggest_files() {
  local ext="$1" n="${2:-5}" want="${3:-impl}"
  find "$REPO_DIR" -type f -name "*.$ext" "${PRUNE[@]}" 2>/dev/null \
    | { if [[ "$want" == "impl" ]]; then
          grep -vE '(_test\.|\.test\.|/tests?/|_spec\.|\.pb\.go$|\.gen\.go$|zz_generated)'
        else
          grep -E '(_test\.|\.test\.|/tests?/|_spec\.)'
        fi; } \
    | xargs wc -l 2>/dev/null | sort -rn | grep -v ' total$' | head -"$n" \
    | awk -v d="$REPO_DIR/" '{ p=$2; sub(d,"",p); printf "| `%s` | %s |\n", p, $1 }' || true   # pipefail: a filter with no match / SIGPIPE from head must not abort the whole probe (hit on nvke, 1000s of .go files)
}

section_header() {
  local slug="$1" head_sha="$2" branch="$3"
  cat <<EOF
# Project facts — ${slug}

> Generated by \`tools/profile-repo.sh\` on $(date -u +%Y-%m-%d) from \`${head_sha}\`
> (branch \`${branch}\`). **Regenerate after any significant merge** — stale facts
> are worse than absent ones, because plans cite them.
>
> Everything here was **probed**, not assumed. Lines marked **⚠ VERIFY** are
> heuristic and must be confirmed before a plan depends on them.

EOF
}

main() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --repo-dir) REPO_DIR="${2:?}"; shift 2 ;;
      --repo)     REPO_SLUG="${2:?}"; shift 2 ;;
      --out)      OUT="${2:?}"; shift 2 ;;
      -h|--help)  usage; exit 0 ;;
      *)          die "unknown option: $1 (try --help)" ;;
    esac
  done

  [[ -d "$REPO_DIR" ]] || die "not a directory: $REPO_DIR"
  command -v git >/dev/null || die "git required"
  REPO_DIR="$(cd "$REPO_DIR" && pwd)"

  local head_sha branch
  head_sha="$(git -C "$REPO_DIR" rev-parse --short HEAD 2>/dev/null || echo 'unknown')"
  branch="$(git -C "$REPO_DIR" rev-parse --abbrev-ref HEAD 2>/dev/null || echo 'unknown')"

  if [[ -z "$REPO_SLUG" ]]; then
    REPO_SLUG="$(git -C "$REPO_DIR" remote get-url origin 2>/dev/null \
      | sed -E 's#(git@[^:]+:|https://[^/]+/)##; s#\.git$##' || true)"
    [[ -n "$REPO_SLUG" ]] || REPO_SLUG="$(basename "$REPO_DIR")"
  fi
  log "probing $REPO_DIR ($REPO_SLUG @ $head_sha)"
  # Facts must describe the mainline, not whatever feature branch is checked out.
  local default_branch
  default_branch="$(git -C "$REPO_DIR" symbolic-ref --short refs/remotes/origin/HEAD 2>/dev/null | sed 's|^origin/||' || true)"
  [[ -n "$default_branch" ]] || default_branch=main
  if [[ "$branch" != "$default_branch" && "$branch" != "HEAD" ]]; then
    warn "on branch '$branch', not '$default_branch' — facts may reflect unmerged work; consider: git -C $REPO_DIR checkout $default_branch"
  fi

  local tmp; tmp="$(mktemp)"
  {
    section_header "$REPO_SLUG" "$head_sha" "$branch"

    # ---------------------------------------------------------------- process
    printf '## Contribution process\n\n'
    local found=0
    for f in CONTRIBUTING.md AGENTS.md CLAUDE.md CODE_OF_CONDUCT.md OWNERS OWNERS_ALIASES \
             .github/PULL_REQUEST_TEMPLATE.md .github/CONTRIBUTING.md docs/development.md \
             docs/testing.md RELEASE.md SECURITY.md; do
      [[ -e "$REPO_DIR/$f" ]] && { printf -- '- `%s`\n' "$f"; found=1; }
    done
    (( found )) || printf -- '- none found — **⚠ VERIFY** how contributions are expected to be made\n'
    printf '\n'

    # Commit-message and PR conventions are the cheapest way to get a PR bounced.
    printf '### Conventions worth knowing before the first PR\n\n'
    if [[ -f "$REPO_DIR/CONTRIBUTING.md" ]]; then
      grep -hoiE "(conventional commit[s]?|signed-off-by|DCO|CLA|squash|rebase|fixes #|closing keyword)" \
        "$REPO_DIR/CONTRIBUTING.md" 2>/dev/null | sort -u | sed 's/^/- mentioned in CONTRIBUTING.md: /' || true
    fi
    [[ -d "$REPO_DIR/.github/workflows" ]] && \
      printf -- '- CI: %s GitHub Actions workflow(s)\n' "$(find "$REPO_DIR/.github/workflows" -name '*.y*ml' 2>/dev/null | wc -l | tr -d ' ')"
    for d in dev/ci/presubmits dev/ci/periodics .prow; do
      [[ -d "$REPO_DIR/$d" ]] && printf -- '- prow jobs in `%s`: %s\n' "$d" "$(ls "$REPO_DIR/$d" 2>/dev/null | wc -l | tr -d ' ')"
    done
    printf '\n'

    # ---------------------------------------------------------------- shape
    printf '## Languages (vendored deps excluded)\n\n| Ext | Files |\n|---|---|\n'
    for ext in go py ts js rs java rb sh yaml md proto; do
      local c; c="$(count_ext "$ext")"
      [[ "$c" -gt 0 ]] && printf '| `.%s` | %s |\n' "$ext" "$c"
    done
    printf '\n> Counts exclude `vendor/`, `node_modules/`, `site-packages/`, `*venv*`,\n'
    printf "> \`__pycache__/\`, \`bin/\`, \`dist/\`, \`build/\`, \`target/\`.\n"
    printf '> An unpruned count can be off by orders of magnitude (on kubernetes-sigs/agent-sandbox it\n'
    printf '> reported 22,012 `.py` files instead of the real 180 — the rest were vendored\n'
    printf '> virtualenvs. **Any counting tool must prune before it counts.**\n\n'

    # ---------------------------------------------------------------- entry points
    printf '## Where to start reading\n\n'
    local primary="" maxc=0
    for ext in go py ts rs java rb; do
      local c; c="$(count_ext "$ext")"
      (( c > maxc )) && { maxc=$c; primary=$ext; }
    done
    if [[ -n "$primary" ]]; then
      printf '### Largest `.%s` implementation files (generated + tests excluded)\n\n| File | Lines |\n|---|---|\n' "$primary"
      biggest_files "$primary" 8 impl
      printf '\n### Largest test files (these double as the behavioural spec)\n\n| File | Lines |\n|---|---|\n'
      biggest_files "$primary" 4 test
      printf '\n'
    fi
    for d in cmd api apis pkg internal controllers src lib app; do
      [[ -d "$REPO_DIR/$d" ]] && printf -- '- `%s/`\n' "$d"
    done
    printf '\n'

    # ---------------------------------------------------------------- build
    printf '## Build & verify\n\n'
    if [[ -f "$REPO_DIR/Makefile" ]]; then
      printf 'Makefile targets:\n\n```\n'
      grep -oE "^[a-zA-Z][a-zA-Z0-9_-]*:" "$REPO_DIR/Makefile" 2>/dev/null | tr -d ':' | sort -u | tr '\n' ' ' | fold -s -w 76
      printf '\n```\n\n'
      printf -- '- **⚠ VERIFY** which target CI actually gates on — often `all`, `verify`, or `test`.\n'
    fi
    for f in package.json pyproject.toml Cargo.toml go.mod pom.xml build.gradle; do
      [[ -f "$REPO_DIR/$f" ]] && printf -- '- manifest: `%s`\n' "$f"
    done
    printf '\n'

    # ---------------------------------------------------------------- generated
    # Editing a generated file by hand is a guaranteed review comment.
    printf '## Generated artifacts — never hand-edit\n\n'
    local gen=0
    while IFS= read -r f; do
      [[ -z "$f" ]] && continue
      printf -- '- `%s`\n' "${f#$REPO_DIR/}"; gen=1
    done < <(grep -rl --include='*.go' --include='*.py' --include='*.ts' \
               -E "^// Code generated by|DO NOT EDIT|@generated" "$REPO_DIR" 2>/dev/null \
             | grep -vE '/(vendor|node_modules|\.git)/' | head -12)
    (( gen )) || printf -- '- none detected by marker scan — **⚠ VERIFY**\n'
    for d in zz_generated api/*/zz_generated.deepcopy.go; do :; done
    printf '\n'
    if [[ -f "$REPO_DIR/Makefile" ]]; then
      printf 'Regeneration targets (match on name):\n\n'
      grep -oE "^[a-zA-Z][a-zA-Z0-9_-]*:" "$REPO_DIR/Makefile" | tr -d ':' \
        | grep -iE "gen|codegen|docs|manifest|mock|proto|fmt" | sed 's/^/- `make /; s/$/`/' | head -10 || \
        printf -- '- none obvious — **⚠ VERIFY**\n'
      printf '\n'
    fi

    # ---------------------------------------------------------------- packaging traps
    printf '## Packaging traps\n\n'
    printf 'Places where adding a file has non-obvious reach. **⚠ VERIFY each before relying on it.**\n\n'
    local trap_found=0
    while IFS= read -r hit; do
      [[ -z "$hit" ]] && continue
      printf -- '- `%s`\n' "${hit#$REPO_DIR/}"; trap_found=1
    done < <(grep -rlE "glob\.glob|\*\*/\*\.ya?ml|filepath\.Walk" "$REPO_DIR/dev" "$REPO_DIR/hack" "$REPO_DIR/scripts" \
               "$REPO_DIR/.github" 2>/dev/null | head -8)
    if (( trap_found )); then
      printf '\n> A glob over a manifest directory means **any file you add there ships by default**.\n'
      printf '> In this repo `dev/tools/release` globs `k8s/**/*.yaml` into release assets, so an\n'
      printf '> "opt-in" manifest placed under `k8s/` would be installed for everyone.\n'
    else
      printf -- '- none detected\n'
    fi
    printf '\n'

    # ---------------------------------------------------------------- how to use
    cat <<'EOF'
## How plans should use this file

1. **Cite it instead of re-deriving.** If a fact is here, reference it rather than
   re-probing; if it is wrong, fix it here so every plan benefits.
2. **Treat ⚠ VERIFY as unproven.** Those are heuristics, not findings.
3. **Regenerate after significant merges.** A stale fact gets copied into plans and
   then into review comments. Line numbers in particular drift constantly — prefer
   symbol names, and re-check any `file:line` before quoting it.
4. **Add facts learned the hard way.** The packaging-trap and generated-artifact
   sections exist because review findings taught them. Append rather than rediscover.
EOF
  } > "$tmp"

  if [[ -n "$OUT" ]]; then
    mv "$tmp" "$OUT"; log "wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
  else
    cat "$tmp"; rm -f "$tmp"
  fi
}

main "$@"
